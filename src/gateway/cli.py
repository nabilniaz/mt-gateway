"""Command-line entry points (installed by `uv sync`, see [project.scripts] in pyproject.toml).

gateway-serve      run the gateway with uvicorn (used by the Docker image)
gateway-token      mint a tenant or admin token offline, for local testing and operators
gateway-init-env   write a local .env with fresh random signing keys
"""

from __future__ import annotations

import argparse
import json
import secrets
import sys
from pathlib import Path

import uvicorn

from gateway.auth import TokenService
from gateway.config import MAX_TOKEN_TTL_SECONDS, Settings
from gateway.pipeline import load_tenants


def serve_main() -> None:
    settings = Settings()
    uvicorn.run(
        "gateway.app:create_app",
        factory=True,
        host=settings.host,
        port=settings.port,
        log_level=settings.log_level.lower(),
        access_log=False,  # the audit log replaces it, and never records query strings
        proxy_headers=False,  # client-IP headers are handled by TRUST_PROXY_HEADERS
        server_header=False,
        timeout_graceful_shutdown=20,  # finish in-flight requests on SIGTERM
    )


def token_main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gateway-token",
        description="Mint a gateway token using the keys in the environment / .env.",
    )
    who = parser.add_mutually_exclusive_group(required=True)
    who.add_argument("--tenant", help="tenant_id to issue a tenant token for")
    who.add_argument("--admin", metavar="OPERATOR", help="issue an admin token for OPERATOR")
    parser.add_argument("--scopes", default="", help="comma-separated scopes (tenant tokens)")
    parser.add_argument("--ttl", type=int, default=MAX_TOKEN_TTL_SECONDS, help="seconds")
    args = parser.parse_args(argv)

    settings = Settings()
    tokens = TokenService(settings)
    try:
        if args.admin:
            print(tokens.issue_admin_token(args.admin, args.ttl).token)
            return 0
        scopes = [s.strip() for s in args.scopes.split(",") if s.strip()]
        tenant = next(
            (t for t in load_tenants(settings.tenants_file) if t.tenant_id == args.tenant), None
        )
        if tenant is None or not tenant.enabled:
            raise ValueError(
                f"tenant {args.tenant!r} is unknown or disabled in {settings.tenants_file}"
            )
        over_grant = sorted(set(scopes) - set(tenant.max_scopes))
        if over_grant:
            raise ValueError(f"scopes not allowed for {args.tenant!r}: {', '.join(over_grant)}")
        print(tokens.issue_tenant_token(args.tenant, scopes, args.ttl).token)
        return 0
    except ValueError as err:
        print(f"error: {err}", file=sys.stderr)
        return 2


def init_env_main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gateway-init-env", description="Write a .env file with fresh random keys."
    )
    parser.add_argument("--path", default=".env")
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    args = parser.parse_args(argv)

    path = Path(args.path)
    if path.exists() and not args.force:
        print(f"{path} already exists; use --force to overwrite", file=sys.stderr)
        return 1
    jwt_keys = json.dumps({"k1": secrets.token_urlsafe(48)})
    path.write_text(
        "# Local development settings. Generated by gateway-init-env. Never commit this file.\n"
        f"GATEWAY_JWT_KEYS='{jwt_keys}'\n"
        f"GATEWAY_ADMIN_KEY={secrets.token_urlsafe(48)}\n"
        "# Local upstreams listen on loopback, which the SSRF guard blocks unless allowlisted.\n"
        "UPSTREAM_ALLOWED_PRIVATE_HOSTS=127.0.0.1,localhost,demo-upstream\n"
        "ROUTES_FILE=config/routes.local.json\n"
    )
    path.chmod(0o600)
    print(f"wrote {path}")
    return 0
